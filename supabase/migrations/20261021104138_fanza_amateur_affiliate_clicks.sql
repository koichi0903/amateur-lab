create table if not exists public.fanza_amateur_affiliate_clicks (
  id bigint generated by default as identity primary key,
  content_id text not null check (char_length(content_id) between 1 and 120),
  source_page text not null check (source_page in ('amateur', 'amateur_detail')),
  placement text not null check (placement in ('listing-card', 'detail-sidebar')),
  affiliate_id text not null check (affiliate_id = 'koichi1928-991'),
  clicked_at timestamptz not null default now()
);

create index if not exists fanza_amateur_affiliate_clicks_clicked_at_idx
  on public.fanza_amateur_affiliate_clicks (clicked_at desc);
create index if not exists fanza_amateur_affiliate_clicks_content_id_idx
  on public.fanza_amateur_affiliate_clicks (content_id, clicked_at desc);
create index if not exists fanza_amateur_affiliate_clicks_attribution_idx
  on public.fanza_amateur_affiliate_clicks (affiliate_id, source_page, placement, clicked_at desc);

alter table public.fanza_amateur_affiliate_clicks enable row level security;
revoke all privileges on table public.fanza_amateur_affiliate_clicks from public, anon, authenticated, service_role;
grant select, insert, update, delete on table public.fanza_amateur_affiliate_clicks to service_role;
grant usage, select on sequence public.fanza_amateur_affiliate_clicks_id_seq to service_role;
