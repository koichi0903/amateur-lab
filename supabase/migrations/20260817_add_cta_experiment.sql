-- Record which purchase CTA copy was clicked. No visitor identifier is stored.
alter table public.affiliate_clicks
  add column if not exists cta_variant text;

alter table public.affiliate_clicks
  drop constraint if exists affiliate_clicks_cta_variant_check;

alter table public.affiliate_clicks
  add constraint affiliate_clicks_cta_variant_check
  check (cta_variant in ('control', 'price-focus'));

-- Keep the database checks aligned with all currently tracked discovery pages
-- and CTA placements.
alter table public.affiliate_clicks
  drop constraint if exists affiliate_clicks_source_page_check;

alter table public.affiliate_clicks
  add constraint affiliate_clicks_source_page_check
  check (source_page in (
    'direct', 'home', 'ranking', 'new', 'sale', 'deals', 'features',
    'comparison', 'search', 'favorites', 'actress', 'genre', 'maker',
    'series', 'related', 'x'
  ));

alter table public.affiliate_clicks
  drop constraint if exists affiliate_clicks_placement_check;

alter table public.affiliate_clicks
  add constraint affiliate_clicks_placement_check
  check (placement in ('detail-sidebar', 'mobile-sticky', 'compare-card'));

create index if not exists affiliate_clicks_cta_variant_clicked_at_idx
  on public.affiliate_clicks (cta_variant, clicked_at desc);

-- Count a CTA only after at least half of it becomes visible. This enables a
-- true click-through-rate comparison without storing visitor identifiers.
create table if not exists public.affiliate_cta_impressions (
  id bigint generated by default as identity primary key,
  work_id bigint not null references public.works(id) on delete cascade,
  placement text not null check (placement in ('detail-sidebar', 'mobile-sticky')),
  source_page text not null check (source_page in (
    'direct', 'home', 'ranking', 'new', 'sale', 'deals', 'features',
    'comparison', 'search', 'favorites', 'actress', 'genre', 'maker',
    'series', 'related', 'x'
  )),
  cta_variant text not null check (cta_variant in ('control', 'price-focus')),
  viewed_at timestamptz not null default now()
);

create index if not exists affiliate_cta_impressions_viewed_at_idx
  on public.affiliate_cta_impressions (viewed_at desc);

create index if not exists affiliate_cta_impressions_variant_viewed_at_idx
  on public.affiliate_cta_impressions (cta_variant, viewed_at desc);

alter table public.affiliate_cta_impressions enable row level security;
revoke all on table public.affiliate_cta_impressions from anon, authenticated;
