create table if not exists public.fanza_amateur_x_post_jobs (
  id bigint generated by default as identity primary key,
  account_handle text not null check (account_handle ~ '^[A-Za-z0-9_]{1,15}$'),
  content_id text not null references public.fanza_amateur_works(content_id) on delete restrict,
  source_lane text not null check (source_lane in ('new_release', 'popular')),
  status text not null default 'pending' check (status in ('pending', 'posted', 'skipped')),
  main_text text not null check (char_length(main_text) between 1 and 280),
  reply_text text not null check (char_length(reply_text) between 1 and 280),
  x_post_url text,
  posted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (account_handle, content_id)
);

create index if not exists fanza_amateur_x_post_jobs_account_created_idx
  on public.fanza_amateur_x_post_jobs (account_handle, created_at desc);
create index if not exists fanza_amateur_x_post_jobs_account_status_idx
  on public.fanza_amateur_x_post_jobs (account_handle, status);

alter table public.fanza_amateur_x_post_jobs enable row level security;
revoke all privileges on table public.fanza_amateur_x_post_jobs from public, anon, authenticated, service_role;
grant select, insert, update, delete on table public.fanza_amateur_x_post_jobs to service_role;
grant usage, select on sequence public.fanza_amateur_x_post_jobs_id_seq to service_role;

