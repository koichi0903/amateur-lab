create table if not exists public.fanza_amateur_performer_matches (
  id bigint generated by default as identity primary key,
  content_id text not null references public.fanza_amateur_works(content_id) on delete cascade,
  performer_name text not null check (char_length(btrim(performer_name)) between 1 and 120),
  source_name text not null check (char_length(btrim(source_name)) between 1 and 120),
  source_url text not null check (source_url ~ '^https://'),
  source_product_code text,
  match_method text not null check (match_method in ('exact_product_code', 'same_work_cross_code', 'manual_review')),
  confidence smallint not null check (confidence between 0 and 100),
  verification_status text not null default 'pending' check (verification_status in ('pending', 'confirmed', 'rejected')),
  evidence_note text,
  source_checked_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (content_id, performer_name, source_name)
);

create index if not exists fanza_amateur_performer_matches_public_lookup_idx
  on public.fanza_amateur_performer_matches (content_id, verification_status, confidence desc);

alter table public.fanza_amateur_performer_matches enable row level security;
revoke all privileges on table public.fanza_amateur_performer_matches from public, anon, authenticated, service_role;
grant select, insert, update, delete on table public.fanza_amateur_performer_matches to service_role;
grant usage, select on sequence public.fanza_amateur_performer_matches_id_seq to service_role;
